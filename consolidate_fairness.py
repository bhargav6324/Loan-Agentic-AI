import sys

def process():
    with open("agents/fairness_agent.py") as f:
        fairness_code = f.read()
    with open("agents/risk_adjustment_agent.py") as f:
        risk_adj_code = f.read()

    # Rename original fairness_agent to _run_fairness_math
    fairness_code = fairness_code.replace("def fairness_agent(", "def _run_fairness_math(")
    
    # Rename original risk_adjustment_agent to _run_fairness_debate
    risk_adj_code = risk_adj_code.replace("def risk_adjustment_agent(", "def _run_fairness_debate(")
    
    def clean_imports(code):
        lines = code.split("\n")
        return "\n".join([l for l in lines if not l.startswith("from ") and not l.startswith("import ")])

    out = '"""\nFairness & Bias Agent — Merged Counterfactual Math & LLM Debate (V6)\n"""\n\n'
    out += "from __future__ import annotations\nimport time\nimport json\nimport httpx\nimport os\n"
    out += "from agents.state import AgentState\nfrom config import settings\nfrom agents.llm_client import call_groq\n"

    out += "\n# --- FAIRNESS MATH LOGIC ---\n" + clean_imports(fairness_code)
    out += "\n# --- FAIRNESS DEBATE LOGIC ---\n" + clean_imports(risk_adj_code)
    
    out += """

def fairness_agent(state: AgentState) -> AgentState:
    \"\"\"
    Consolidated Fairness Agent.
    1. Runs the counterfactual math.
    2. If any bias gaps > 5 points are found, immediately triggers the LLM debate.
    \"\"\"
    state = _run_fairness_math(state)
    
    # Check if there are challenges generated by the math
    challenges = state.get("fairness_challenges", [])
    if challenges:
        # Trigger the debate internally!
        state = _run_fairness_debate(state)
        
    return state
"""
    with open("agents/fairness_agent_new.py", "w") as f:
        f.write(out)

if __name__ == "__main__":
    process()
